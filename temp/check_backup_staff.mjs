import fs from 'fs';
const d = fs.readdirSync('supabase-v2/backup').filter(f => f.startsWith('v2-')).sort().pop();
console.log('DIR:', d);
const s = JSON.parse(fs.readFileSync('supabase-v2/backup/' + d + '/staff_profiles.json', 'utf8'));
console.log('OLD STAFF COUNT:', s.length);
s.forEach(u => console.log(' ', u.username, '|', u.full_name, '|', u.role, '|', u.id));
const r = JSON.parse(fs.readFileSync('supabase-v2/backup/' + d + '/reports.json', 'utf8'));
console.log('REPORTS TOTAL:', r.length);
const byDoc = {};
r.forEach(x => { byDoc[x.doctor_id] = (byDoc[x.doctor_id] || 0) + 1; });
console.log('BY doctor_id:', JSON.stringify(byDoc));
const byCr = {};
r.forEach(x => { byCr[x.created_by] = (byCr[x.created_by] || 0) + 1; });
console.log('BY created_by:');
Object.entries(byCr).forEach(([k, v]) => console.log(' ', k, v));
