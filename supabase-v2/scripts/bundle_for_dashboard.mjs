/* =====================================================================
 *  bundle_for_dashboard.mjs
 * ---------------------------------------------------------------------
 *  The Supabase dashboard editor deploys ONE file, so a relative import
 *  like `../_shared/auth.ts` cannot resolve there. Two ways to deploy v2:
 *
 *    A. Supabase CLI (keeps the tree as-is, bundles imports for you)
 *         supabase functions deploy auth-admin
 *    B. No CLI (the situation on this workstation right now): paste the
 *       generated bundle instead.
 *         node bundle_for_dashboard.mjs
 *         -> dist/auth-admin.bundle.ts
 *         -> dist/patient-photos.bundle.ts
 *       Open the bundle, select all, paste into the editor. Nothing else
 *       changes: the code below is byte-identical to the source, with the
 *       shared module pasted above it and the import line removed.
 *
 *  The bundle is then run through the SAME parser as parse_check.mjs, so
 *  "it pasted" and "it compiles" are the same statement. A bundle that
 *  would fail to deploy fails HERE first — including the case where the
 *  shared module and a function declare the same identifier.
 * ===================================================================== */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const acorn = require('acorn')

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(HERE, '..')
const FN_DIR = join(ROOT, 'edge-functions')
const OUT_DIR = join(ROOT, 'dist')
const SHARED = join(FN_DIR, '_shared', 'auth.ts')
const FUNCTIONS = ['auth-admin', 'patient-photos']
const SHARED_RE = /^import\s*\{([\s\S]*?)\}\s*from\s*'\.\.\/_shared\/auth\.ts'\s*$/m

const shared = readFileSync(SHARED, 'utf8')

/** Names the shared module actually exports. */
const exported = new Set()
for (const m of shared.matchAll(/^export\s+(?:async\s+)?(?:function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) {
  exported.add(m[1])
}

if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true })
let failed = 0

for (const name of FUNCTIONS) {
  const src = readFileSync(join(FN_DIR, name, 'index.ts'), 'utf8')
  const hit = SHARED_RE.exec(src)
  if (!hit) {
    console.log(`  FAIL  ${name}: no \`from '../_shared/auth.ts'\` import found`)
    failed++
    continue
  }

  // 1. Every imported name must exist in the shared module, otherwise the
  //    bundle throws a ReferenceError at cold start that the editor shows
  //    only after you have already deployed it.
  const wanted = hit[1].split(',').map(s => s.trim()).filter(Boolean)
  const missing = wanted.filter(n => !exported.has(n))
  if (missing.length) {
    console.log(`  FAIL  ${name}: imports ${missing.join(', ')} — not exported by _shared/auth.ts`)
    failed++
    continue
  }

  // 2. Replace the import with nothing. The shared code goes above, so the
  //    identifiers resolve in the same module scope.
  const inlined = src.replace(SHARED_RE, '').replace(/^\s*\n/, '')
  const banner = [
    '// =====================================================================',
    `//  ${name}  ·  single-file bundle for the dashboard editor`,
    '//  GENERATED by scripts/bundle_for_dashboard.mjs — DO NOT EDIT.',
    '//  Edit edge-functions/' + name + '/index.ts and',
    '//  edge-functions/_shared/auth.ts, then re-run the bundler.',
    '// =====================================================================',
    '',
  ].join('\n')

  const bundle = banner + shared.trimEnd() + '\n\n' + inlined.trimStart()
  const outPath = join(OUT_DIR, `${name}.bundle.ts`)
  writeFileSync(outPath, bundle, 'utf8')

  // 3. The bundle must parse on its own.
  let report = `  ok    ${name.padEnd(15)} dist/${name}.bundle.ts (${(bundle.length / 1024).toFixed(1)}kb, ${wanted.length} shared symbols inlined)`
  try {
    acorn.parse(bundle, { ecmaVersion: 'latest', sourceType: 'module' })
  } catch (e) {
    report = `  FAIL  ${name}: bundle does not parse — ${e.message}`
    failed++
  }
  console.log(report)
}

console.log(failed
  ? `\n==== ${failed} BUNDLE(S) REJECTED ====\n`
  : `\n==== BUNDLES READY ====\n  Deploy: dashboard > Edge Functions > Edit > paste dist/<name>.bundle.ts\n  Keep "Verify JWT" OFF — the functions check the JWT themselves.\n`)
process.exitCode = failed ? 1 : 0
